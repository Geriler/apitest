/**
 * Описание типа детали: всё, что отличает резистор от светодиода, — в одном месте.
 * Сама деталь в схеме — простые данные (Component, сохраняются как JSON); поведение —
 * в описании её типа (PARTS[c.type]). Новая деталь = новый файл в этой папке + строка в index.ts.
 */

import type { Component, Pin, Scene } from "../model/types";
import type { Load, Simulation } from "../sim/simulation";
import type { Branch, Extras } from "../sim/solver";
import type { Tolerance } from "../sim/tolerance";
import type { ComponentView, Visual } from "../view/kit";

/** Куда деталь складывает свои ветви для решателя. */
export interface Stamp {
  out: Branch[];
  extras: Required<Extras>;
  /** Идеальные соединения узлов (начинка микросхемы с её выводами). */
  links: [string, string][];
}

/** Перегрев: выше порога «тепло» копится со скоростью (нагрузка − порог)·rate, ниже — остывает. */
export interface Thermal {
  threshold: number;
  rate: number;
  cooling: number;
}

/** Обозначение трёхвыводной детали на схеме: основной путь вертикально, управляющий вывод слева. */
export interface Symbol3 {
  /** Выводы: верх основного пути (коллектор, сток), управляющий (база, затвор), низ (эмиттер, исток). */
  roles: { up: Pin; ctrl: Pin; down: Pin };
  /** Обозначение в своей системе координат: круг радиусом 17 с центром в начале координат. */
  body: string;
  /** Где линия управляющего вывода касается обозначения, по x. */
  ctrlX: number;
}

/** Данные новой детали без обозначения и места: { type, ...параметры }. */
export type NewPart<C extends Component> = C extends Component ? Omit<C, "id" | "placement"> : never;

/**
 * Инструмент установки детали: кнопка в группе на панели слева, горячие клавиши и настройки
 * новой детали (панель справа, пока инструмент выбран).
 */
export interface ToolDef<C extends Component = Component, S = any> {
  /** Имя инструмента (data-tool): "tht", "cap"… */
  id: string;
  /** Группа кнопок на панели слева; без группы кнопки нет (инструмент скрыт). */
  group?: "passive" | "semi" | "load" | "power" | "instruments" | "chips" | "kit";
  /** Значок: содержимое <svg viewBox="0 0 30 18">. */
  icon: string;
  /** Подпись кнопки и всплывающая подсказка. */
  label: string;
  title: string;
  /** Начальные настройки новой детали; меняются полями панели (set). */
  settings: S;
  /** Заголовок панели новой детали. */
  name(s: S): string;
  /** Пояснение и поля настройки в панели новой детали. */
  note(s: S): string;
  editor(s: S): string;
  set(s: S, field: string, value: string): void;
  /** Данные новой детали. */
  create(s: S): NewPart<C>;
  /** Поправить только что поставленную деталь по схеме (например, взять следующий свободный номер). */
  adjust?(c: C, scene: Scene): void;
  /** Подсказка внизу экрана; pending — отверстие, где уже стоит первый вывод. */
  hint(s: S, pending?: string): string;
  /** Почему нельзя поставить в плату (если деталь не встаёт в плату). */
  boardRefusal?: string;
}

/**
 * Описать инструмент детали C: тип настроек выводится из поля settings.
 * toolFor<Diode>()({ id: "diode", settings: { kind: "1N4007" }, … })
 */
export const toolFor =
  <C extends Component>() =>
  <S>(t: ToolDef<C, S>): ToolDef<C, S> =>
    t;

/**
 * Одно обозначение детали на схеме. Обычно деталь — одно обозначение; реле — два: катушка и контакты
 * (по ГОСТ они рисуются отдельно). Двухвыводное обозначение — symbol, трёхвыводное — symbol3
 * (его roles — номера выводов самой детали).
 */
export interface SchematicPart {
  /** Имя для ручной раскладки (у основного обозначения — пусто). */
  key: string;
  /** Выводы детали, к которым подключено обозначение (2 или 3). */
  pins: Pin[];
  symbol?: string;
  symbol3?: Symbol3;
  /** Буквы в центре двухвыводного обозначения. */
  text?: string;
  /** Одновыводное обозначение — флажок с подписью на линии цепи. */
  flag?: { text: string; color: string };
  /** Многовыводное — прямоугольник с подписями выводов (по порядку pins). */
  box?: string[];
  /** Подпись под обозначением детали. */
  value: string;
  /** Ток для подписи, А. */
  current: number;
}

export interface PartDef<C extends Component = Component> {
  type: C["type"];
  /** Буква обозначения по ЕСКД: R, C, VD, HL, VT, SA, GB, G. */
  prefix: string;
  /** Число выводов. */
  pins: number;
  /** Сколько места деталь занимает в корпусе микросхемы, клеток (по умолчанию 1). */
  chipSpace?(c: C, scene: Scene): number;
  /** Как считать деталь в составе микросхемы: вид («резистор», «BC547») и транзистор ли это. */
  countAs?(c: C): { name: string; transistor?: boolean };
  /** Почему деталь не может быть внутри микросхемы (не помещается или теряет смысл); нет — может. */
  notInChip?(c: C): string | undefined;
  /** Число выводов у этого экземпляра, если оно своё у каждого (микросхемы). */
  pinCount?(c: C): number;
  /** Встаёт ли в плату (у SMD-резистора нет ножек, батарея и блок питания — на столе). */
  onBoard(c: C): boolean;
  /** Инструменты установки на панели слева (у резистора — выводной и SMD). */
  tools: ToolDef<C>[];
  /** Важно ли, какой вывод куда (тогда деталь можно перевернуть клавишей F). */
  polar(c: C): boolean;
  /** Короткая подпись в списке деталей. */
  label(c: C): string;
  /** Номинал для подписи на принципиальной схеме. */
  value(c: C): string;
  /**
   * Обозначение на схеме для двухвыводной детали, в своей системе координат: вывод 0 вверху
   * (y = −20), вывод 1 внизу (y = 20). У трёхвыводных (транзисторы) — своя отрисовка.
   */
  symbol?(c: C): string;
  /** Номинальная мощность, Вт (для перегрева по мощности), если есть. */
  rated?(c: C): number;
  /** Заголовок и пояснение уведомления, когда деталь выходит из строя. */
  burn(c: C): [string, string];
  /**
   * Обозначение трёхвыводной детали на схеме (обязательно, если выводов три).
   */
  symbol3?(c: C): Symbol3;
  /** Несколько обозначений на схеме вместо одного (катушка и контакты реле). */
  schematicParts?(c: C, sim: Simulation): SchematicPart[];
  /** Названия выводов для подписей проводов: «COM», «NO»… (по умолчанию «вывод N»). */
  pinLabels?: string[];
  /** То же, если название зависит от детали (цоколёвка MOSFET, выводы микросхемы). */
  pinLabel?(c: C, pin: number, scene: Scene): string;
  /** Буквы в обозначении на схеме (V, A, Ω): рисуются не переворачиваясь, в центре обозначения. */
  symbolText?(c: C): string;
  /** Цвета проводов «авто» от выводов детали на столе: у батареи — чёрный к минусу, красный к плюсу. */
  leadColors?: string[];
  /** Источник питания: на схеме его плюс (вывод 1) — верхняя цепь, минус (вывод 0) — нижняя. */
  source?: boolean;
  /** 3D-вид детали на столе или на плате (без припоя — его добавляет builders.ts). */
  view(c: C): ComponentView;

  // ─── Расчёт ─────────────────────────────────────────────────────────────

  /**
   * Ветви детали для решателя при текущих линеаризациях (sim.junction) и шаге sim.h.
   * Вызывается и для сгоревшей детали: она сама решает, что от неё остаётся (обычно — обрыв).
   */
  stamp(c: C, sim: Simulation, s: Stamp): void;
  /**
   * Шаг Ньютона после очередного решения: обновить свои переходы в sim.junction.
   * Возвращает true, если деталь сошлась. Только у нелинейных деталей и только у исправных.
   */
  newton?(c: C, sim: Simulation, iter: number, shared: { flips: number }): boolean;
  /** Есть ли у детали ёмкости (тогда время идёт шагами и нужен remember). */
  dynamic?: boolean;
  /** После шага по времени: запомнить заряд своих ёмкостей в sim.capVoltage. */
  remember?(c: C, sim: Simulation): void;
  /** Напряжение между выводами 0 и 1, В (по умолчанию — по своей ветви). */
  voltage?(c: C, sim: Simulation): number;
  /** Ток от вывода 0 к выводу 1, А (по умолчанию — по своей ветви). */
  current?(c: C, sim: Simulation): number;
  /** Мощность, которая выделяется теплом, Вт (по умолчанию — по своей ветви). */
  power?(c: C, sim: Simulation): number;
  /** Ток для подписи на схеме (по умолчанию — ток от вывода 0 к выводу 1). */
  schematicCurrent?(c: C, sim: Simulation): number;
  /** Запасённая энергия, Дж (у конденсатора). */
  energy?(c: C, sim: Simulation): number;
  /** Нагрузка относительно предела (для перегрева и панели). */
  load?(c: C, sim: Simulation): Load | undefined;
  thermal?: Thermal;
  /** Короткое замыкание (для батареи — искры). */
  shorted?(c: C, sim: Simulation): boolean;
  /** Включена наоборот и напряжение приложено против неё. */
  reversed?(c: C, sim: Simulation): boolean;

  // ─── Вид и управление ────────────────────────────────────────────────────

  /** Что показать на 3D-модели, кроме нагрева: яркость свечения, показания дисплея. */
  visual?(c: C, sim: Simulation): Partial<Visual>;
  /** Переключить: тумблер, выход блока питания (кнопка data-act="toggle" в панели). */
  toggle?(c: C): void;
  /** Кнопка без фиксации: нажатие указателем держит её замкнутой до отпускания (Simulation.held). */
  momentary?: boolean;
  /** Обычный щелчок переключает деталь (toggle), а не выделяет её. */
  clickToggles?: boolean;

  // ─── Панель свойств ─────────────────────────────────────────────────────

  /** Заголовок, пояснение и поля настройки (поля показываются только у выбранной детали). */
  panel(c: C, sim: Simulation): { title: string; body: string; editor?: string };
  /** Изменить параметр из поля панели (select data-field="…"). */
  edit?(c: C, field: string, value: string): void;
  /** Показания вверху панели (по умолчанию U, I, P). */
  readout?(c: C, sim: Simulation): string;
  /** Плашка исправной и не перегруженной детали (по умолчанию «НОРМА»). */
  status?(c: C, sim: Simulation): string;
  /** Как сказать «сгорел» на плашке (по умолчанию «СГОРЕЛ»). */
  burnedWord?: string;
  /** Плашка, когда деталь включена наоборот (sim.isReversed). */
  reversedPill?: string;
  /** Плашка, когда нагрузка близка к пределу (по умолчанию «ГРЕЕТСЯ»). */
  warmWord?(ratio: number): string;
  /** Работа у предела — норма (лампа, светодиод): шкала нагрузки не желтеет. */
  nearLimitOk?: boolean;
  /** Названия выводов 0 и 1 полярной двухвыводной детали, по умолчанию «анод», «катод». */
  pinNames?: [string, string];
  /** Подпись «где стоят выводы» на плате, если нужна своя (у трёхвыводных). */
  where?(c: C, holes: string[]): string;
  /** Нельзя перевернуть: у батареи и блока питания выводы подписаны. */
  noFlip?: boolean;
  /** Строки «фактически» — параметры этого экземпляра при включённых допусках. */
  actual?(c: C, tol: Tolerance): string;
}
